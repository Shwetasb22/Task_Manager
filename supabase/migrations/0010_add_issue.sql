-- "Add issue" from the app.
-- Until now rows were created only by the import (seed.sql / service role). This migration lets a
-- Manager add an issue to THEIR OWN tracker and an Admin add to any tracker. Everything is enforced
-- by Postgres, so the browser cannot bypass it. Owners still cannot create issues.
-- Apply after 0009. Safe to re-run.

begin;

-- ───────────── who may insert ─────────────
drop policy if exists tasks_insert on public.tasks;
create policy tasks_insert on public.tasks for insert to authenticated
with check (
     public.app_role() = 'admin'
  or (public.app_role() = 'manager' and manager = public.app_manager()) 
  
);

-- ───────────── next issue id, e.g. SI-205 ─────────────
-- Reuses the prefix already used by that tracker (SI-, AB-, VS-, YD-, AK-). For a brand-new tracker
-- it falls back to the manager's initials. The number is max+1 across the whole table, because the
-- id is the primary key. An advisory lock stops two people adding at the same moment from getting
-- the same number.
create or replace function public.next_task_id(p_manager text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_prefix text;
  v_next   integer;
begin
  select split_part(t.id, '-', 1) into v_prefix
  from public.tasks as t
  where t.manager = p_manager and t.id ~ '^[A-Za-z]+-[0-9]+$'
  limit 1;

  if v_prefix is null then
    select upper(string_agg(left(w, 1), '')) into v_prefix
    from regexp_split_to_table(regexp_replace(btrim(p_manager), '[^A-Za-z ]', '', 'g'), '\s+') as w
    where w <> '';
    if v_prefix is null or length(v_prefix) < 2 then
      v_prefix := upper(left(regexp_replace(coalesce(p_manager, 'XX'), '[^A-Za-z]', '', 'g') || 'XX', 2));
    end if;
  end if;

  perform pg_advisory_xact_lock(hashtext('tasks_next_id:' || v_prefix));

  select coalesce(max(substr(t.id, length(v_prefix) + 2)::integer), 0) + 1 into v_next
  from public.tasks as t
  where t.id like v_prefix || '-%'
    and substr(t.id, length(v_prefix) + 2) ~ '^[0-9]{1,9}$';

  return v_prefix || '-' || v_next;
end;
$$;

-- ───────────── rules applied to every new row ─────────────
create or replace function public.tasks_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  r text;
begin
  new.program     := btrim(new.program);
  new.description := btrim(new.description);
  new.owner       := coalesce(nullif(btrim(new.owner), ''), 'Unassigned');
  new.dept        := coalesce(nullif(btrim(new.dept), ''), 'Unassigned');

  if new.manager is null or btrim(new.manager) = '' then
    raise exception using errcode = '23514', message = 'An issue must belong to a tracker.';
  end if;

  if auth.uid() is not null then
    -- signed-in user (browser): restrictions apply, and the id is always generated by the database
    r := public.app_role();
    if r is null or r not in ('admin', 'manager') then
      raise exception using errcode = '42501', message = 'Only a Manager or Admin can add issues.';
    end if;
    if new.program = '' then
      raise exception using errcode = '23514', message = 'Program is required.';
    end if;
    if new.description = '' then
      raise exception using errcode = '23514', message = 'Issue description is required.';
    end if;
    if new.closed_date is not null then
      raise exception using errcode = '23514',
        message = 'A new issue cannot be created as closed. Attach proof, then close it.';
    end if;
    if new.start_date is not null and new.due_date is not null and new.due_date < new.start_date then
      raise exception using errcode = '23514', message = 'Target date cannot be before the start date.';
    end if;
    new.id := public.next_task_id(new.manager);
    new.updated_by := auth.uid();
  elsif new.id is null or btrim(new.id) = '' then
    -- SQL editor / service role import without an id
    new.id := public.next_task_id(new.manager);
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_before_insert_trg on public.tasks;
create trigger tasks_before_insert_trg
  before insert on public.tasks
  for each row execute function public.tasks_before_insert();

-- ───────────── audit trail: who created the issue ─────────────
create or replace function public.tasks_log_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null then
    insert into public.task_events (task_id, actor, actor_name, action, detail)
    values (new.id, auth.uid(), public.app_name(), 'created',
            jsonb_build_object('manager', new.manager, 'program', new.program, 'owner', new.owner,
                               'dept', new.dept, 'due_date', new.due_date));
  end if;
  return null;
end;
$$;

drop trigger if exists tasks_log_insert_trg on public.tasks;
create trigger tasks_log_insert_trg
  after insert on public.tasks
  for each row execute function public.tasks_log_insert();

commit;
